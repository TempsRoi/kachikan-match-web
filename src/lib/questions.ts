export function worldFor(answers: number[]) {
  const totals = Array(8).fill(0);
  answers.forEach((a, i) => {
    totals[(a + i) % 8] += 2;
    totals[(a * 2 + i + 3) % 8] += 1;
  });
  return worlds[totals.indexOf(Math.max(...totals))];
}
export function closeness(a: number[], b: number[]) {
  return Math.round(
    (a.reduce(
      (s, v, i) => s + (v === b[i] ? 2 : Math.abs(v - b[i]) === 1 ? 1 : 0),
      0,
    ) /
      (questions.length * 2)) *
      100,
  );
}
